/** Scratch address the probe code is placed at for the call. Holds nothing on-chain. */
export const ROUTE_PROBE_ADDRESS = '0x00000000000000000000000000000000004c3456' as Address;

/** `UniversalRouterSwapAdapter.allowedCaller` storage slot (`forge inspect ... storageLayout`). */
const ALLOWED_CALLER_SLOT = 2n;

/** Storage key of `allowedCaller[caller]` on the adapter, and the value that allows it. */
export function allowedCallerOverride(caller: Address): {
  slot: Hex;
  value: Hex;
} {
  const slot = keccak256(
    encodeAbiParameters([{ type: 'address' }, { type: 'uint256' }], [caller, ALLOWED_CALLER_SLOT])
  );
  return { slot, value: pad('0x01', { size: 32 }) };
}

