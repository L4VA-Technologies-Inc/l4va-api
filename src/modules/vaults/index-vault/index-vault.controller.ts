import {
  BadRequestException,
  Body,
  Controller,
  Get,
  NotFoundException,
  Param,
  ParseUUIDPipe,
  Post,
  Put,
  Query,
  UseGuards,
} from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiQuery, ApiSecurity, ApiTags } from '@nestjs/swagger';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { isAddress, type Address } from 'viem';

import { IndexBasketReq } from './dto/index-basket.dto';
import { IndexSwapRouteService } from './index-swap-route.service';
import { IndexVaultService } from './index-vault.service';
import { SupportedTokensService } from './supported-tokens.service';
import { ReplaceSupportedTokensReq, type SupportedTokensRes } from './supported-tokens.types';

import { Vault } from '@/database/vault.entity';
import { AdminGuard } from '@/modules/auth/admin.guard';
import { AuthGuard } from '@/modules/auth/auth.guard';

@ApiTags('Index vaults')
@Controller('vaults')
export class IndexVaultController {
  constructor(
    private readonly indexVaultService: IndexVaultService,
    private readonly routeService: IndexSwapRouteService,
    private readonly supportedTokens: SupportedTokensService,
    @InjectRepository(Vault) private readonly vaultRepository: Repository<Vault>
  ) {}

  @Get(':id/swap-cap')
  @ApiOperation({
    summary: "How much of an asset the vault's swap adapter lets it sell right now",
    description:
      '`capBps` is the share of the vault balance it may sell per 24 h (the allowance refills gradually); ' +
      '`remaining` is the raw amount sellable now. `guarded: false` means the adapter has no cap. ' +
      'Native ETH is the zero address.',
  })
  @ApiQuery({ name: 'asset', required: true })
  async getSwapCap(
    @Param('id', ParseUUIDPipe) vaultId: string,
    @Query('asset') asset: string
  ): ReturnType<IndexSwapRouteService['sellCap']> {
    if (!asset || !isAddress(asset)) throw new BadRequestException(`Invalid asset address: ${asset}`);
    const vault = await this.vaultRepository.findOne({
      where: { id: vaultId },
      select: ['id', 'chain_id', 'evm_protocol_version', 'contract_address'],
    });
    if (!vault?.contract_address) throw new NotFoundException('Vault has no on-chain contract');
    return this.routeService.sellCap(vault, asset.toLowerCase() as Address);
  }

  @Get('index/assets')
  @ApiOperation({
    summary: 'Tokens an index basket may hold',
    description: 'When `restricted` is false any token the swap adapter can quote is accepted.',
  })
  getSupportedAssets(): ReturnType<IndexVaultService['getSupportedAssets']> {
    return this.indexVaultService.getSupportedAssets();
  }

  @Get('index/supported-tokens')
  @ApiOperation({
    summary: 'Tokens index vaults can trade today (public)',
    description:
      'Reviewed list behind the /supported-tokens page: each token trades through allowlisted Uniswap pools. ' +
      '`liquidity` thin means small vaults only. Generated by swap-pool-review.ts.',
  })
  getSupportedTokens(): Promise<SupportedTokensRes> {
    return this.supportedTokens.list();
  }

  @Put('index/supported-tokens')
  @UseGuards(AdminGuard)
  @ApiSecurity('Admin-Token')
  @ApiOperation({
    summary: 'Replace the supported-tokens list (admin)',
    description: 'Called by swap-pool-review.ts with PUBLISH_URL. Replaces every token of this chain.',
  })
  replaceSupportedTokens(@Body() body: ReplaceSupportedTokensReq): Promise<{ count: number }> {
    return this.supportedTokens.replace(body);
  }

  @Get('index/assets/:address/routes')
  @UseGuards(AuthGuard)
  @ApiBearerAuth()
  @ApiOperation({
    summary: 'Whether a token can be bought with ETH and sold back to ETH through Uniswap',
    description:
      "Uses the same routing as trade execution. Pass `vaultId` to check with that vault's swap adapter; " +
      'without it the check is for a new vault. `status` is ok, no_route or unavailable (Uniswap did not answer).',
  })
  @ApiQuery({ name: 'vaultId', required: false })
  checkAssetRoutes(
    @Param('address') address: string,
    @Query('vaultId') vaultId?: string
  ): ReturnType<IndexVaultService['checkAssetRoutes']> {
    return this.indexVaultService.checkAssetRoutes(address, vaultId || undefined);
  }

  @Get(':id/index')
  @ApiOperation({
    summary: 'Index-weighted vault basket, live allocation and rebalance history',
    description: 'Holdings are valued by swap quotes into native and cached for one minute.',
  })
  getIndexOverview(@Param('id', ParseUUIDPipe) vaultId: string): ReturnType<IndexVaultService['getOverview']> {
    return this.indexVaultService.getOverview(vaultId);
  }

  @Post(':id/index/preview')
  @UseGuards(AuthGuard)
  @ApiBearerAuth()
  @ApiOperation({
    summary: 'Estimate the trades a re-weight to this basket would make',
    description:
      'Resolves every basket asset on chain and reads the live portfolio, so it is restricted to authenticated callers.',
  })
  previewReweight(
    @Param('id', ParseUUIDPipe) vaultId: string,
    @Body() body: IndexBasketReq
  ): ReturnType<IndexVaultService['previewReweight']> {
    return this.indexVaultService.previewReweight(vaultId, body.targets, body.reserveBps);
  }

  @Post(':id/index/rebalances/:rebalanceId/retry')
  @UseGuards(AdminGuard)
  @ApiSecurity('Admin-Token')
  @ApiOperation({ summary: 'Operator retry of a failed basket rebalance' })
  retryRebalance(
    @Param('id', ParseUUIDPipe) vaultId: string,
    @Param('rebalanceId', ParseUUIDPipe) rebalanceId: string
  ): ReturnType<IndexVaultService['retryRebalance']> {
    return this.indexVaultService.retryRebalance(vaultId, rebalanceId);
  }
}
